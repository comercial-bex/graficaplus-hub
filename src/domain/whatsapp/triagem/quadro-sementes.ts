import type { Casamento, Intencao, RespostaDoQuadro } from "./tipos";

/**
 * Sementes do quadro de respostas, com a escrita real do português do Brasil.
 *
 * É a lista inicial de `whatsapp_triagem_respostas` (PR B1). O quadro é DADO:
 * o dono acrescenta frases pela tela, nunca intenções. Toda frase aqui já está
 * normalizada (minúsculas, sem acento, sem pontuação); um teste garante que
 * `normalizarTexto(frase) === frase` para todas.
 *
 * Regras de escolha do casamento:
 *  - letra solta e abreviação ("s", "n", "ss"): `igual`;
 *  - palavra que abre a resposta ("sim", "claro", "pode"): `comeca`;
 *  - frase que pode aparecer no meio ("quero mudar", "quanto custa"): `contem`.
 *
 * A palavra "revendedor" NÃO existe aqui, de propósito: o dono só tem duas
 * modalidades, parceiro (terceirizado) e cliente final.
 */

function L(
  intencao: Exclude<Intencao, "nao_sei">,
  passo: string | null,
  casamento: Casamento,
  frases: string[],
): RespostaDoQuadro[] {
  return frases.map((frase) => ({ passo, intencao, frase, casamento, ativo: true }));
}

