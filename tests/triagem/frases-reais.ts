/** Variações de escrita que não mudam a intenção: caixa alta com exclamações, sem acento, e com cumprimento na frente. */
export function variar(base: string): string[] {
  const semAcento = base.normalize("NFD").replace(/\p{M}/gu, "");
  return [base, `${base.toUpperCase()}!!!`, semAcento, `oi, ${base}`];
}
